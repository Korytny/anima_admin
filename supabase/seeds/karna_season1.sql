## Сквозной вопрос
Кто я — сын царицы или сын возничего? В каждой серии Карна делает один необратимый выбор. Посеянное в ранних сериях стреляет в поздних: проклятия (2 → 10), доспех (1, 6 → 9, 10), тайна матери (1 → 7, 8), долг Дурьодхане (3 → 7), оскорбление Драупади (4, 5 → 10).

## Информационная асимметрия
Зритель с первой серии знает то, чего герои не знают до седьмой: Карна — сын Кунти и старший брат Пандавов. Каждая сцена, где Пандавы унижают «сына возничего», а Арджуна клянётся убить Карну, для зрителя — брат против брата. Тайну героям не раскрываем раньше серии 7; зрителю даём её видеть (серьги, взгляд Кунти, знак солнца).

## Тон
Сдержанная трагедия. Не эпос с придыханием, а история людей, которые хотят простых вещей: признания, безопасности, чести. Боги ведут себя как люди.

## Правила диалогов
- В каждой реплике персонаж чего-то ХОЧЕТ от собеседника: просит, прогоняет, врёт, торгуется, оправдывается. Никаких деклараций.
- Тему вслух не произносить. Запрещены слова: судьба, предназначение, ответ, одиночество, свет, тьма; «имя» как символ.
- Запрещены афоризмы и фразы «для обложки».
- До 8–10 слов в реплике. Разговорная речь, можно перебивать и обрывать фразу.
- Половина сцен — без слов. Действие и деталь сильнее объяснения.
- Каноничные реплики из первоисточника сохраняем — они сильнее выдуманных.

